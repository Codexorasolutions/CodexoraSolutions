// ============================================================
// SINGLE SHARED HEADER — edit this one file and every page updates.
//
// What lives here:
//   • the top navigation bar (logo, links, "Get Started" button)
//   • the mobile slide-in menu + hamburger behaviour
//   • "active page" highlighting (done automatically)
//
// How it's used: each page just contains
//     <div id="site-header"></div>
//     <script src="header.js"></script>          (index.html)
//     <script src="../header.js"></script>       (pages/*.html)
// placed where the old <nav> used to be.
//
// It works from both the site root and /pages/*, and also when
// pages are opened directly from disk (file://) — no fetch needed.
// ============================================================

(function () {
  // ─────────────── 1. EDIT THESE ───────────────

  // Paths are written relative to the SITE ROOT. The script adds
  // the right "../" or "pages/" prefix automatically.
  const LOGO = { src: "logo.png", alt: "Codexora Solutions", href: "index.html" };

  const LINKS = [
    { label: "Home",     href: "index.html" },
    { label: "Services", href: "pages/services.html" },
    { label: "Process",  href: "pages/process.html" },
    { label: "Pricing",  href: "pages/pricing.html" },
    { label: "Work",     href: "pages/work.html" },
    { label: "About",    href: "pages/about.html" },
    { label: "Contact",  href: "pages/contact.html" },
  ];

  const CTA = { label: "Get Started", href: "pages/contact.html" };

  // External link to the client portal. Full URL, used as-is
  // (it is NOT passed through url(), so no "../" gets added).
  const LOGIN = { label: "Client Login", href: "https://client-login-portal-gilt.vercel.app" };

  // ─────────────── 2. LOGIC (no need to edit) ───────────────

  const mount = document.getElementById("site-header");
  if (!mount) return;

  // Are we inside /pages/ ? If so, links back to the root need "../".
  const inPages = location.pathname.includes("/pages/");
  const root = inPages ? "../" : "";
  // From inside /pages/, links to other pages are just "about.html";
  // everything else (index, logo, ...) gets the "../" prefix.
  const url = (href) =>
    inPages && href.startsWith("pages/") ? href.slice("pages/".length) : root + href;

  // Page "slug" for matching: "/pages/about.html" or "/pages/about" -> "about"
  const slugOf = (path) => {
    const last = path.split("?")[0].split("#")[0].split("/").pop() || "index";
    return last.replace(/\.html$/i, "") || "index";
  };
  const currentSlug = slugOf(location.pathname);

  const isActive = (href) => slugOf(href) === currentSlug;

  const desktopLinks = LINKS.map(
    (l) =>
      `<li><a href="${url(l.href)}"${isActive(l.href) ? ' class="active"' : ""}>${l.label}</a></li>`
  ).join("\n    ");

  const mobileLinks = LINKS.map(
    (l) => `<a href="${url(l.href)}">${l.label}</a>`
  ).join("\n  ")
    + `\n  <a href="${LOGIN.href}">${LOGIN.label}</a>`;

  mount.outerHTML = `
<!-- NAV (generated by header.js) -->
<nav>
  <a href="${url(LOGO.href)}" class="logo" aria-label="${LOGO.alt} home">
    <img src="${url(LOGO.src)}" alt="${LOGO.alt}">
  </a>
  <ul class="nav-links">
    ${desktopLinks}
  </ul>
  <div class="nav-actions">
    <a href="${LOGIN.href}" class="nav-login">${LOGIN.label}</a>
    <a href="${url(CTA.href)}" class="nav-cta">${CTA.label}</a>
  </div>
  <button class="hamburger" id="hamburgerBtn" aria-label="Open menu" aria-expanded="false">
    <span></span><span></span><span></span>
  </button>
</nav>

<!-- MOBILE NAV (generated by header.js) -->
<div class="mobile-nav" id="mobileNav">
  <button class="mobile-close" id="mobileClose" aria-label="Close menu">&times;</button>
  ${mobileLinks}
</div>`;

  // Mobile menu open / close
  const menu = document.getElementById("mobileNav");
  const openBtn = document.getElementById("hamburgerBtn");
  const closeBtn = document.getElementById("mobileClose");

  const setOpen = (open) => {
    menu.classList.toggle("open", open);
    openBtn.setAttribute("aria-expanded", String(open));
  };

  openBtn.addEventListener("click", () => setOpen(true));
  closeBtn.addEventListener("click", () => setOpen(false));
  menu.querySelectorAll("a").forEach((a) =>
    a.addEventListener("click", () => setOpen(false))
  );
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") setOpen(false);
  });
})();
